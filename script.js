function renderLines(id, lines) {
  const box = document.getElementById(id);
  box.replaceChildren();

  lines.forEach(line => {
    const p = document.createElement("p");
    p.textContent = line;
    if (/^[A-Za-z]/.test(line)) p.classList.add("english");
    box.appendChild(p);
  });
}

function renderVocabulary(words) {
  const box = document.getElementById("vocabularyContent");
  box.replaceChildren();

  const title = document.createElement("h3");
  title.textContent = "واژگان جدید";
  box.appendChild(title);

  const table = document.createElement("table");
  table.innerHTML = "<thead><tr><th>English</th><th>معنی فارسی</th></tr></thead>";

  const tbody = document.createElement("tbody");

  words.forEach(word => {
    const row = document.createElement("tr");
    const en = document.createElement("td");
    const fa = document.createElement("td");

    en.textContent = word[0];
    en.classList.add("english");
    fa.textContent = word[1];

    row.append(en, fa);
    tbody.appendChild(row);
  });

  table.appendChild(tbody);
  box.appendChild(table);
}

function renderPractice(questions) {
  const box = document.getElementById("practiceContent");
  box.replaceChildren();

  const title = document.createElement("h3");
  title.textContent = "تمرین";
  box.appendChild(title);

  questions.forEach(item => {
    const questionBox = document.createElement("div");
    questionBox.className = "question";

    const p = document.createElement("p");
    p.textContent = item.question;

    const button = document.createElement("button");
    button.textContent = "نمایش جواب";
    button.type = "button";

    const answer = document.createElement("p");
    answer.className = "answer";
    answer.textContent = item.answer;

    button.addEventListener("click", () => {
      const visible = answer.style.display === "block";
      answer.style.display = visible ? "none" : "block";
      button.textContent = visible ? "نمایش جواب" : "مخفی کردن جواب";
    });

    questionBox.append(p, button, answer);
    box.appendChild(questionBox);
  });
}

function showSection(id) {
  document.querySelectorAll(".section").forEach(section => {
    section.classList.toggle("active", section.id === id);
  });

  document.querySelectorAll(".section-buttons button").forEach(button => {
    button.classList.toggle("active", button.dataset.section === id);
  });
}

function selectLesson(index) {
  const lesson = lessons[index];
  if (!lesson) return;

  document.getElementById("lessonTitle").textContent = lesson.title;
  document.getElementById("lessonIntro").textContent = lesson.intro;

  document.querySelectorAll(".lesson-buttons button").forEach(button => {
    button.classList.toggle("active", Number(button.dataset.lesson) === index);
  });

  renderLines("overviewContent", lesson.overview);
  renderVocabulary(lesson.vocabulary);
  renderLines("grammarContent", lesson.grammar);
  renderLines("conversationContent", lesson.conversation);
  renderPractice(lesson.practice);

  showSection("overview");
}

document.querySelectorAll(".lesson-buttons button").forEach(button => {
  button.addEventListener("click", () => {
    selectLesson(Number(button.dataset.lesson));
  });
});

document.querySelectorAll(".section-buttons button").forEach(button => {
  button.addEventListener("click", () => {
    showSection(button.dataset.section);
  });
});

selectLesson(0);
